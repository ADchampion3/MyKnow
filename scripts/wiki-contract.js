import assert from "node:assert/strict";
import { spawn } from "node:child_process";
import fs from "node:fs";

const port = 3031;
const databaseFile = `apps/api/data/wiki-contract-${process.pid}.db`;
const storage = `data/wiki-contract-storage-${process.pid}`;
fs.mkdirSync("apps/api/data", { recursive: true });
fs.closeSync(fs.openSync(databaseFile, "w"));
const child = spawn(process.execPath, ["apps/api/src/nest.js"], { env: { ...process.env, API_PORT: String(port), DATABASE_URL: `file:./${databaseFile}`, RESOURCE_STORAGE_DIR: storage }, stdio: "ignore" });
const base = `http://127.0.0.1:${port}`;
const request = async (path, options) => { const response = await fetch(base + path, options); const body = response.status === 204 ? {} : await response.json(); return { response, body }; };
const json = (value) => JSON.stringify(value);
const headers = { "content-type": "application/json" };
const waitForHealth = async () => { for (let i = 0; i < 200; i += 1) { try { if ((await fetch(`${base}/health`)).ok) return; } catch {} await new Promise((resolve) => setTimeout(resolve, 100)); } throw new Error("API did not start"); };

try {
  await waitForHealth();
  const created = await request("/api/knowledge-bases", { method: "POST", headers, body: json({ name: "Wiki contract KB" }) });
  assert.equal(created.response.status, 201);
  const kbId = created.body.data.id;
  const overview = await request(`/api/knowledge-bases/${kbId}/wiki`);
  assert.equal(overview.response.status, 200);
  assert.equal(overview.body.data.defaultPath, "index/overview");
  assert.equal(overview.body.data.empty, true);
  assert.equal(overview.body.data.pageCount, 0);
  const templates = await request(`/api/knowledge-bases/${kbId}/wiki/templates`);
  assert.equal(templates.body.data.length, 4);
  const space = await request(`/api/knowledge-bases/${kbId}/spaces`, { method: "POST", headers, body: json({ name: "Contract space" }) });
  assert.equal(space.response.status, 201);
  const source = await request("/api/resources", { method: "POST", headers, body: json({ name: "source.md", content: "\uFEFFImmutable source\r\ntext", knowledgeBaseId: kbId }) });
  assert.equal(source.response.status, 201);
  const retrievalOnly = await request("/api/resources", { method: "POST", headers, body: json({ name: "scan.pdf.txt", content: "Search-only source", knowledgeBaseId: kbId, wikiMode: "retrieval-only" }) });
  assert.equal(retrievalOnly.response.status, 201);
  assert.equal(retrievalOnly.body.data.resource.wikiMode, "retrieval-only");
  const page = await request(`/api/knowledge-bases/${kbId}/wiki/pages`, { method: "POST", headers, body: json({ title: "Contract concept", slug: "contract-concept", pageType: "concept", spaceId: space.body.data.id, contentMarkdown: "# Contract concept\n\n## Definition\n\nOld answer", citations: [{ resourceVersionId: source.body.data.version.id, locator: { startOffset: 0, endOffset: 10 } }] }) });
  assert.equal(page.response.status, 201);
  const pageId = page.body.data.id;
  const firstVersionId = page.body.data.currentVersionId;
  assert.equal(page.body.data.currentVersion.citations.length, 1);
  const citationId = page.body.data.currentVersion.citations[0].id;
  const citationPreview = await request(`/api/wiki/citations/${citationId}/preview`);
  assert.equal(citationPreview.response.status, 200);
  assert.match(citationPreview.body.data.snippet, /Immutable source\ntext/);
  assert.deepEqual(citationPreview.body.data.range, { startOffset: 0, endOffset: 10, contextStart: 0, contextEnd: 21 });
  const invalidCitation = await request(`/api/wiki/pages/${pageId}/citations`, { method: "POST", headers, body: json({ resourceVersionId: source.body.data.version.id, locator: { startOffset: 0, endOffset: 999 } }) });
  assert.equal(invalidCitation.response.status, 400);
  assert.equal(invalidCitation.body.error.code, "WIKI_CITATION_INVALID");
  const invalidPageCitation = await request(`/api/wiki/pages/${pageId}/citations`, { method: "POST", headers, body: json({ resourceVersionId: source.body.data.version.id, locator: { page: 2 } }) });
  assert.equal(invalidPageCitation.response.status, 400);
  assert.equal(invalidPageCitation.body.error.code, "WIKI_CITATION_INVALID");
  const edited = await request(`/api/wiki/pages/${pageId}/versions`, { method: "POST", headers, body: json({ baseVersionId: firstVersionId, contentMarkdown: "# Contract concept\n\n## Definition\n\nNew answer\n\nAdded line", changeSummary: "second edit" }) });
  assert.equal(edited.response.status, 201);
  assert.ok(edited.body.data.diff === undefined);
  const secondVersionId = edited.body.data.id;
  assert.equal(edited.body.data.citations.length, 1);
  const missingBase = await request(`/api/wiki/pages/${pageId}/versions`, { method: "POST", headers, body: json({ contentMarkdown: "missing base" }) });
  assert.equal(missingBase.response.status, 400);
  assert.equal(missingBase.body.error.code, "VALIDATION_ERROR");
  const conflict = await request(`/api/wiki/pages/${pageId}/versions`, { method: "POST", headers, body: json({ baseVersionId: firstVersionId, contentMarkdown: "stale" }) });
  assert.equal(conflict.response.status, 409);
  assert.equal(conflict.body.error.code, "WIKI_VERSION_CONFLICT");
  const diff = await request(`/api/wiki/pages/${pageId}/diff?fromVersionId=${firstVersionId}&toVersionId=${secondVersionId}`);
  assert.equal(diff.response.status, 200);
  assert.ok(diff.body.data.diff.added.some((line) => line.includes("New answer")));
  assert.ok(diff.body.data.diff.removed.some((line) => line.includes("Old answer")));
  const restored = await request(`/api/wiki/pages/${pageId}/restore`, { method: "POST", headers, body: json({ versionId: firstVersionId, baseVersionId: secondVersionId }) });
  assert.equal(restored.response.status, 201);
  assert.equal(restored.body.data.restoreOfVersionId, firstVersionId);
  const versions = await request(`/api/wiki/pages/${pageId}/versions`);
  assert.equal(versions.body.data.length, 3);
  const metadataRejected = await request(`/api/wiki/pages/${pageId}`, { method: "PATCH", headers, body: json({ contentMarkdown: "must not overwrite" }) });
  assert.equal(metadataRejected.body.error.code, "WIKI_PAGE_METADATA_ONLY");
  const metadata = await request(`/api/wiki/pages/${pageId}`, { method: "PATCH", headers, body: json({ title: "Contract concept renamed", slug: "contract-concept-renamed", spaceId: space.body.data.id }) });
  assert.equal(metadata.response.status, 200);
  assert.equal(metadata.body.data.currentVersionId, restored.body.data.id);
  assert.equal(metadata.body.data.slug, "contract-concept-renamed");
  const sourceRejected = await request(`/api/resources/${source.body.data.resource.id}`, { method: "PATCH", headers, body: json({ content: "must not mutate" }) });
  assert.equal(sourceRejected.body.error.code, "RESOURCE_READ_ONLY");
  const sourceDeleteRejected = await request(`/api/resources/${source.body.data.resource.id}`, { method: "DELETE" });
  assert.equal(sourceDeleteRejected.body.error.code, "RESOURCE_READ_ONLY");
  const customTemplate = await request(`/api/knowledge-bases/${kbId}/wiki/templates`, { method: "POST", headers, body: json({ pageType: "entity", definition: { sections: [{ title: "Custom", required: true, description: "Custom section" }] } }) });
  assert.equal(customTemplate.response.status, 201);
  const secondPage = await request(`/api/knowledge-bases/${kbId}/wiki/pages`, { method: "POST", headers, body: json({ title: "Custom entity", pageType: "entity", parentPageId: pageId }) });
  assert.equal(secondPage.response.status, 201);
  assert.notEqual(secondPage.body.data.currentVersion.templateVersionId, page.body.data.currentVersion.templateVersionId);
  assert.equal(secondPage.body.data.parentPageId, pageId);
  const cyclePage = await request(`/api/knowledge-bases/${kbId}/wiki/pages`, { method: "POST", headers, body: json({ title: "Child", pageType: "concept", parentPageId: pageId }) });
  assert.equal(cyclePage.response.status, 201);
  const cycle = await request(`/api/wiki/pages/${pageId}`, { method: "PATCH", headers, body: json({ parentPageId: cyclePage.body.data.id }) });
  assert.equal(cycle.response.status, 409);
  assert.equal(cycle.body.error.code, "WIKI_PAGE_CYCLE");
  const impacts = await request(`/api/knowledge-bases/${kbId}/wiki/impacts`);
  assert.equal(impacts.response.status, 200);
  assert.equal(impacts.body.data.count, 0);
  const other = await request("/api/knowledge-bases", { method: "POST", headers, body: json({ name: "Other KB" }) });
  assert.equal(other.response.status, 201);
  const finalOverview = await request(`/api/knowledge-bases/${kbId}/wiki`);
  assert.equal(finalOverview.body.data.pageCount, 3);
  assert.ok(!finalOverview.body.data.log.events.some((event) => event.entity_id === other.body.data.id));
  assert.ok(finalOverview.body.data.candidates.some((candidate) => candidate.id === source.body.data.resource.id));
  assert.ok(!finalOverview.body.data.candidates.some((candidate) => candidate.id === retrievalOnly.body.data.resource.id));
  console.log(JSON.stringify({ status: "passed", pageId, versions: versions.body.data.length, citationId }));
} finally {
  child.kill();
}
